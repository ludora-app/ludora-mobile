export type PaginatedMessagesResponse = {
  data: Message[];
  nextCursor: number | null;
  hasMore: boolean;
  total: number;
};

export type FetchMessagesParams = {
  pageParam?: number;
  limit?: number;
};

// Fake fetch function for React Query infinite query
export const fetchMessages = async ({
  limit = 10,
  pageParam = 0,
}: FetchMessagesParams): Promise<PaginatedMessagesResponse> => {
  // Simulate network delay
  await new Promise(resolve => {
    setTimeout(resolve, 500);
  });

  const start = pageParam * limit;
  const end = start + limit;

  // Reverse the array to show newest messages first (typical chat behavior)
  const reversedMessages = [...mockMessages].reverse();

  const paginatedData = mockMessages.slice(start, end);

  const hasMore = end < mockMessages.length;
  const nextCursor = hasMore ? pageParam + 1 : null;

  return {
    data: paginatedData,
    hasMore,
    nextCursor,
    total: mockMessages.length,
  };
};

// Alternative: Cursor-based pagination (using message UID)
export type CursorPaginatedMessagesResponse = {
  data: Message[];
  nextCursor: string | null;
  hasMore: boolean;
  total: number;
};

export type FetchMessagesCursorParams = {
  cursor?: string;
  limit?: number;
};

export const fetchMessagesWithCursor = async ({
  cursor,
  limit = 10,
}: FetchMessagesCursorParams): Promise<CursorPaginatedMessagesResponse> => {
  // Simulate network delay
  await new Promise(resolve => {
    setTimeout(resolve, 500);
  });

  const reversedMessages = [...mockMessages].reverse();

  let startIndex = 0;
  if (cursor) {
    const cursorIndex = reversedMessages.findIndex(msg => msg.uid === cursor);
    startIndex = cursorIndex !== -1 ? cursorIndex + 1 : 0;
  }

  const paginatedData = reversedMessages.slice(startIndex, startIndex + limit);
  const hasMore = startIndex + limit < reversedMessages.length;
  const nextCursor = hasMore && paginatedData.length > 0 ? paginatedData[paginatedData.length - 1].uid : null;

  return {
    data: paginatedData,
    hasMore,
    nextCursor,
    total: mockMessages.length,
  };
};
